#!/usr/bin/env python3
"""Write the EXACT text the LangGraph agents received, for every wording and scheme, to prompts_final/.

The prompts/ and prompts_v*/ folders hold the briefing of the first (archived) run, in which agents played
through shell commands. The final runs (Claude Haiku 5.5, Llama 3.1) use the system prompt in
langchain_sim/run_langgraph.py instead. This script rebuilds that text from the same sources the runner uses,
so it can never drift from the code.

Run: python sim/export_final_prompts.py
"""
import random, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "sim"))
import setup_agents as sa, newsvendor_env as env
from prompt_variants import get_instr, strip_bonus

src = (ROOT / "langchain_sim" / "run_langgraph.py").read_text(encoding="utf-8")
system_tpl = re.search(r'\("system",\s*"""(.*?)"""\)\]\)', src, re.S).group(1)
debrief = re.search(r"HumanMessage\(content='(Final questions\..*?)'\)", src, re.S).group(1)
out = ROOT / "prompts_final"; out.mkdir(exist_ok=True)

for w in ["base", "v1", "v2", "v3"]:
    instr = get_instr(w, sa.INSTR)
    for c in ["O", "C"]:
        (out / f"system_{w}_{c}.txt").write_text(strip_bonus(system_tpl.format(instr=instr[c]), w), encoding="utf-8")

def day1(cond, faithful, q=11):
    env.FAITHFUL = faithful; env.rng = random.Random(7)          # fixed dice for the example only
    s = dict(id="EX", cond=cond, cash=env.START_CASH, rounds=[], debrief=None)
    first = env.prompt(s); fb = env.play(s, q)
    return (f"[Message to the agent at the start of day 1]\n{first}\n\n[Agent's structured answer]\nI order {q} units.\n\n"
            f"[Message after the dice; it ends with the prompt for day 2]\n{fb}\n\n{env.prompt(s)}\n")

for c in ["O", "C"]:
    (out / f"example_day_main_{c}.txt").write_text(day1(c, False), encoding="utf-8")
    (out / f"example_day_faithful_{c}.txt").write_text(day1(c, True), encoding="utf-8")
(out / "debrief.txt").write_text(debrief + "\n", encoding="utf-8")
(out / "README.md").write_text("""# Exact prompts of the final runs

Generated by `python sim/export_final_prompts.py` from the code the runner uses, so they match the runs exactly.

| File | What it is |
| --- | --- |
| `system_<wording>_<O|C>.txt` | System prompt each agent received (base = the study's text word for word; v1, v2, v3 = robustness wordings) |
| `example_day_main_<O|C>.txt` | One example day as the agent saw it in the main runs (with the daily net-change line) |
| `example_day_faithful_<O|C>.txt` | The same day in the human-like feedback run (`--faithful`): two payments, no net line, the study's C wording |
| `debrief.txt` | The end-of-game questions. Question (1), the original follow-up question, was added for the human-like feedback run; the main runs asked (2) to (4) |

The dice in the examples are fixed for illustration only; in the runs they are random. The `prompts/` and `prompts_v*/`
folders hold the briefing of the first, archived run, where agents played through shell commands.
""", encoding="utf-8")
print("wrote", sorted(p.name for p in out.iterdir()))
